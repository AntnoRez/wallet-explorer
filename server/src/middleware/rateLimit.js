/**
 * Ограничение частоты запросов к нашему API.
 *
 * ЗАЧЕМ. Наш сервер стоит перед чужими ключами, и без ограничения любой
 * желающий может дёргать его в цикле, пока не кончится суточная квота
 * Etherscan или Helius. Ключи именные — расплачиваться будем мы.
 *
 * ДВА УРОВНЯ, И ОНИ ПРО РАЗНОЕ.
 *
 *   здесь            частота обращений С ОДНОГО АДРЕСА
 *   services/apiBudget.js   суммарный расход ключей
 *
 * Одного первого мало: десяток адресов или один человек через прокси
 * выберут квоту, оставаясь каждый в своём лимите. Одного второго тоже
 * мало: он сработает, когда квота уже на исходе, и остановит всех сразу,
 * включая добросовестных.
 *
 * ПОЧЕМУ ЛИМИТА ДВА, А НЕ ОДИН. Запросы стоят по-разному:
 *
 *   отдать граф из базы        десятки миллисекунд, чужие API не трогаем
 *   ?refresh или новый адрес   секунды и десяток обращений наружу
 *
 * Общий лимит бережёт наш процесс, строгий — чужие квоты.
 */

import { rateLimit } from 'express-rate-limit';

import { config } from '../config/env.js';

/** Окно учёта — минута. Короче нельзя: всплеск при открытии страницы */
const WINDOW_MS = 60 * 1000;

/**
 * Ответ при превышении.
 *
 * Формат тот же, что у остальных ошибок API: фронт показывает `message`
 * как есть, и человек должен понять, что произошло и что делать.
 */
function tooMany(_req, res) {
  res.status(429).json({
    error: 'Слишком много запросов. Подождите минуту и попробуйте снова',
    retryAfterSeconds: Math.ceil(WINDOW_MS / 1000),
  });
}

const common = {
  windowMs: WINDOW_MS,
  standardHeaders: 'draft-7',
  legacyHeaders: false,
  handler: tooMany,
};

/**
 * Общий лимит на все запросы.
 *
 * Шестьдесят в минуту — это запрос в секунду непрерывно. Живой человек
 * столько не делает: раскрытие узла, переход, смена фильтра — пять-пятнадцать
 * обращений в минуту при активной работе.
 */
export const generalLimiter = rateLimit({
  ...common,
  limit: config.server.rateLimitPerMinute,
});

/**
 * Строгий лимит для запросов, которые идут во внешние API.
 *
 * Сюда попадают:
 *   - ?refresh — принудительное обновление, всегда идёт наружу;
 *   - ?loadMore — догрузка истории, тоже всегда;
 *   - POST /labels — ходит в TronScan порциями.
 *
 * Обычный просмотр адреса под этот лимит НЕ подпадает, хотя при первом
 * обращении тоже идёт наружу: иначе исследование графа упёрлось бы
 * в потолок на десятом узле. От перебора адресов защищает предохранитель
 * бюджета.
 */
export const externalLimiter = rateLimit({
  ...common,
  limit: config.server.rateLimitExternalPerMinute,
});

/**
 * Выбрать лимитер по признакам запроса.
 *
 * Отдельная прослойка, а не два `app.use` подряд: строгий лимит должен
 * применяться ВМЕСТО общего, а не вдобавок к нему. Иначе дорогой запрос
 * тратил бы сразу два счётчика.
 */
export function apiLimiter(req, res, next) {
  const isExpensive =
    req.query.refresh !== undefined ||
    req.query.loadMore !== undefined ||
    req.method === 'POST';

  return isExpensive ? externalLimiter(req, res, next) : generalLimiter(req, res, next);
}
