/**
 * Адрес кошелька или контракта.
 *
 * Таблица служит двум разным целям, и их важно не путать:
 *
 *  1. Журнал синхронизации — когда мы последний раз ходили за этим адресом
 *     во внешний API и на чём остановились (lastFetchedAt, syncState).
 *  2. Наши собственные данные об адресе — метка, результат эвристики.
 *
 * Баланса здесь нет и не должно быть.
 *
 * Во-первых, он устаревает в момент записи — следующая транзакция его меняет.
 *
 * Во-вторых, из наших переводов его НЕ ВЫЧИСЛИТЬ, даже имея полную историю:
 * мимо списка проходят комиссии за энергию и пропускную способность,
 * заморозка TRX под ресурсы, награды, делегирование. Сумма переводов — это
 * сальдо переводов, а не баланс, и оно всегда расходится с реальностью.
 *
 * Правильный источник — отдельный запрос GET /v1/accounts/{address}:
 * поле balance (свободный TRX в SUN), массив trc20 (балансы токенов) и
 * frozenV2 (замороженное под ресурсы). Запрашивается при обращении к
 * адресу, в БД не сохраняется.
 */

import { DataTypes } from 'sequelize';
import { sequelize } from '../config/database.js';

export const Address = sequelize.define(
  'Address',
  {
    /**
     * Ключ сети из config/networks.js. Строка, а не числовой chainId:
     * у Tron chainId в EVM-смысле не существует.
     *
     * Часть составного первичного ключа: один и тот же адрес существует
     * в разных сетях с разной историей.
     */
    network: {
      type: DataTypes.STRING(32),
      primaryKey: true,
      allowNull: false,
    },

    /**
     * Адрес в КАНОНИЧЕСКОЙ форме сети. Для Tron это base58 (T...).
     *
     * ВНИМАНИЕ: приводить к нижнему регистру нельзя — base58
     * регистрозависим. Нормализация только через
     * services/normalize/tronAddress.js.
     */
    address: {
      type: DataTypes.STRING(64),
      primaryKey: true,
      allowNull: false,
    },

    /**
     * Человекочитаемая метка: «Binance-Hot 1», «Kucoin 4».
     * Источник — публичная разметка TronScan (publicTag).
     */
    label: {
      type: DataTypes.STRING(128),
      allowNull: true,
    },

    /**
     * Когда мы спрашивали метку.
     *
     * Нужен ровно по той же причине, что и lastFetchedAt: отличить
     * «метки нет» от «ещё не спрашивали».
     *
     *   label=null, labelFetchedAt=null    -> не спрашивали, надо сходить
     *   label=null, labelFetchedAt=вчера   -> спрашивали, метки нет
     *   label="Binance-Hot 1"              -> знаем
     *
     * Без этого поля мы дёргали бы TronScan при каждом появлении обычного
     * кошелька в графе — а таких большинство, и меток у них нет.
     */
    labelFetchedAt: {
      type: DataTypes.DATE,
      allowNull: true,
    },

    /**
     * Прочая разметка TronScan: метки риска и поведенческие теги.
     *
     *   { "redTag": "", "greyTag": "", "blueTag": "",
     *     "chainTags": ["High Balance", "Large Trader"] }
     *
     * Держим ОТДЕЛЬНО от isSuspicious: одно дело «мы обнаружили паттерн
     * дробления» (наш вывод, который можно проверить), другое — «TronScan
     * считает адрес подозрительным» (чужое мнение). В интерфейсе это
     * разные значки, смешивать их нельзя.
     */
    tags: {
      type: DataTypes.JSONB,
      allowNull: true,
    },

    /**
     * Когда мы ПОЛНОСТЬЮ выкачивали этот адрес.
     *
     * null означает, что адрес известен только косвенно — встретился как
     * контрагент в чужой транзакции. У такого адреса в нашей базе лежат
     * далеко не все его переводы, и считать его закэшированным нельзя.
     *
     * Это различие критично: без него граф врал бы — кликнул на узел,
     * «данные есть», показали два ребра вместо двадцати.
     */
    lastFetchedAt: {
      type: DataTypes.DATE,
      allowNull: true,
    },

    /**
     * Приватное состояние синхронизации провайдера: курсоры пагинации,
     * отметки времени. Никто, кроме провайдера этой сети, внутрь не смотрит —
     * контроллер только хранит и отдаёт обратно.
     *
     * Для Tron у каждого источника СВОЙ курсор:
     *   { "trx":      { "fingerprint": "...", "lastTimestamp": 1786542054000 },
     *     "trc20":    { "fingerprint": "...", "lastTimestamp": 1786540758000 },
     *     "internal": { "lastTimestamp": 1786540758000 } }
     *
     * JSONB, а не колонки: у EVM-сетей пагинация по номеру блока, у TronGrid
     * курсорная. Новая сеть с четвёртым видом пагинации не потребует миграции.
     */
    syncState: {
      type: DataTypes.JSONB,
      allowNull: true,
    },

    /** Результат эвристики дробления средств */
    isSuspicious: {
      type: DataTypes.BOOLEAN,
      allowNull: false,
      defaultValue: false,
    },

    /**
     * Почему помечен подозрительным — текст для подсказки в интерфейсе.
     * Без объяснения красная обводка на узле бесполезна: пользователь
     * не может ни проверить вывод, ни возразить ему.
     */
    suspicionReason: {
      type: DataTypes.STRING(256),
      allowNull: true,
    },
  },
  {
    tableName: 'addresses',
    indexes: [
      // Поиск адресов, которые пора обновить, и отбор ранее выкачанных
      { fields: ['network', 'lastFetchedAt'] },
    ],
  },
);

export default Address;
